"""F8 feedback loop: list negative feedback (with trace IDs for Jaeger), approve items into
the golden set (new version number) or reject them.

  make feedback-review                         → list new 👎 feedback
  uv run jobscout feedback-review --approve 12 → append to eval/golden.yaml, bump version
  uv run jobscout feedback-review --reject 13
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from typing import Any

import yaml
from sqlalchemy import select, update

from jobscout.db.engine import session_scope
from jobscout.db.models import Feedback
from jobscout.settings import REPO_ROOT

GOLDEN = REPO_ROOT / "eval" / "golden.yaml"


def append_to_golden(items: list[Feedback], path: Path = GOLDEN) -> int:
    """Append approved feedback as new questions; returns the new golden version."""
    header = "# Golden evaluation set. Generated by eval/build_golden.py.\n"
    data: dict[str, Any] = (
        yaml.safe_load(path.read_text(encoding="utf-8"))
        if path.exists()
        else {"version": 0, "questions": []}
    )
    existing = {q["id"] for q in data["questions"]}
    for fb in items:
        qid = f"fb-{fb.id:04d}"
        if qid in existing:
            continue
        data["questions"].append(
            {
                "id": qid,
                "category": "from_feedback",
                "lang": "de"
                if any(
                    w in fb.question.lower() for w in (" und ", " die ", " der ", "welche", "wie ")
                )
                else "en",
                "question": fb.question,
                "expected_tools": [],
                "feedback": {
                    "rating": fb.rating,
                    "comment": fb.comment,
                    "trace_id": fb.trace_id,
                    "bad_answer": fb.answer[:1000],
                },
            }
        )
    data["version"] = int(data.get("version", 0)) + 1
    data["updated_at"] = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
    path.write_text(
        header + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=120),
        encoding="utf-8",
    )
    return int(data["version"])


async def review(
    approve: list[int] | None = None, reject: list[int] | None = None, path: Path = GOLDEN
) -> dict[str, Any]:
    approve, reject = approve or [], reject or []
    async with session_scope() as s:
        if approve:
            items = (
                (await s.execute(select(Feedback).where(Feedback.id.in_(approve)))).scalars().all()
            )
            version = append_to_golden(list(items), path)
            await s.execute(
                update(Feedback).where(Feedback.id.in_(approve)).values(review_status="approved")
            )
            print(f"appended {len(items)} item(s) to {path.name}; golden version is now {version}")
        if reject:
            await s.execute(
                update(Feedback).where(Feedback.id.in_(reject)).values(review_status="rejected")
            )
        await s.commit()
        pending = (
            (
                await s.execute(
                    select(Feedback)
                    .where(Feedback.rating < 0, Feedback.review_status == "new")
                    .order_by(Feedback.created_at)
                )
            )
            .scalars()
            .all()
        )
    for fb in pending:
        print(f"#{fb.id}  {fb.created_at:%Y-%m-%d %H:%M}  trace={fb.trace_id or '-'}")
        print(f"   Q: {fb.question[:200]}")
        print(f"   A: {fb.answer[:200].replace(chr(10), ' ')}")
        print(f"   comment: {fb.comment or '-'}")
    if not pending:
        print("no new negative feedback")
    return {"pending": len(pending), "approved": len(approve), "rejected": len(reject)}
